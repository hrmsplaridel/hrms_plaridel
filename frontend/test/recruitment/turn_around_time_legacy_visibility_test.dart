import 'package:flutter_test/flutter_test.dart';
import 'package:hrms_plaridel/features/learning_development/models/turn_around_time.dart';
import 'package:hrms_plaridel/features/recruitment/presentation/admin/sections/turn_around_time_section.dart';

const _legacyIds = [
  '277b88d7-5fb4-4d50-b4e4-3f2e615b29e6',
  '8740109e-dac1-41f6-a5f7-959b6e653792',
  'b208dd40-b419-4373-b63e-f50b56d1c54e',
  'fe3f740a-3c6f-4117-a8a9-5ebe5cb8a6db',
  'cdeebdfa-f0a3-40bd-9585-94c0b2d75643',
  '3c4d87b9-4eed-420c-aec6-fb02b79f66b5',
];

const _protectedId = '81797789-df70-44eb-9cb3-fcd0519e2964';

TurnAroundTimeEntry _entry({
  String? id,
  String? position,
  String? office,
  String? applicantName,
}) {
  return TurnAroundTimeEntry(
    id: id,
    position: position,
    office: office,
    applicants: [
      if (applicantName != null) TurnAroundTimeApplicant(name: applicantName),
    ],
  );
}

void main() {
  test('excludes only the six legacy ids and keeps every other row', () {
    final loaded = [
      for (final id in _legacyIds)
        _entry(id: id, position: null, office: null, applicantName: 'Legacy'),
      _entry(
        id: _protectedId,
        position: 'IT Coder',
        office: null,
        applicantName: 'Lord Wampipti',
      ),
      _entry(id: 'aaaaaaaa-bbbb-4ccc-8ddd-eeeeeeeeeeee', position: 'Clerk'),
      _entry(id: '11111111-2222-4333-8444-555555555555', office: null),
      _entry(id: '66666666-7777-4888-8999-aaaaaaaaaaaa', position: null, office: 'HR'),
      _entry(position: 'New manual form', office: 'Mayor'),
      _entry(
        id: '99999999-aaaa-4bbb-8ccc-dddddddddddd',
        position: null,
        office: null,
        applicantName: 'Legacy',
      ),
    ];

    final visible = visibleTurnAroundTimeEntries(loaded);
    final visibleIds = visible.map((e) => e.id).toList();

    expect(legacyAutoGeneratedTatRecordIds, hasLength(6));
    for (final id in _legacyIds) {
      expect(visibleIds, isNot(contains(id)));
      expect(
        isLegacyAutoGeneratedTatRecord(_entry(id: id.toUpperCase())),
        isTrue,
      );
    }
    expect(visibleIds, contains(_protectedId));
    expect(visibleIds, contains('aaaaaaaa-bbbb-4ccc-8ddd-eeeeeeeeeeee'));
    expect(visibleIds, contains('11111111-2222-4333-8444-555555555555'));
    expect(visibleIds, contains('66666666-7777-4888-8999-aaaaaaaaaaaa'));
    expect(visible.any((e) => e.id == null && e.position == 'New manual form'), isTrue);
    expect(visibleIds, contains('99999999-aaaa-4bbb-8ccc-dddddddddddd'));
    expect(visible, hasLength(6));
    expect(
      visible.singleWhere((e) => e.id == _protectedId).office,
      isNull,
    );
    expect(
      visible.singleWhere((e) => e.id == '66666666-7777-4888-8999-aaaaaaaaaaaa').position,
      isNull,
    );
  });

  test('an all-legacy load is an empty visible list', () {
    final visible = visibleTurnAroundTimeEntries([
      for (final id in _legacyIds) _entry(id: id),
    ]);
    expect(visible, isEmpty);
  });

  test('filtering again does not change the visible list', () {
    final loaded = [
      for (final id in _legacyIds) _entry(id: id),
      _entry(id: _protectedId, position: 'IT Coder'),
    ];
    final once = visibleTurnAroundTimeEntries(loaded);
    final twice = visibleTurnAroundTimeEntries(once);
    expect(twice.map((e) => e.id).toList(), [ _protectedId ]);
    expect(twice, hasLength(once.length));
  });
}
