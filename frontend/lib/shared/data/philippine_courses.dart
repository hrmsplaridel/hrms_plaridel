/// Search text so short names such as "BS Nursing" or "BEED" still match.
String philippineCourseSearchText(String course) {
  final lower = course.toLowerCase();
  final extra = StringBuffer(lower);

  void alias(String prefix, String abbreviation) {
    if (!lower.startsWith(prefix)) return;
    extra.write(' $abbreviation ${lower.substring(prefix.length)}');
  }

  alias('bachelor of science in ', 'bs');
  alias('bachelor of science ', 'bs');
  alias('bachelor of arts in ', 'ab ba');
  alias('bachelor of arts ', 'ab ba');
  alias('bachelor of elementary education', 'beed');
  alias('bachelor of secondary education', 'bsed');
  alias('bachelor of early childhood education', 'beced');
  alias('bachelor of physical education', 'bped');
  alias('bachelor of special needs education', 'bsned');
  alias('bachelor of library and information science', 'blis');
  alias('bachelor of technical-vocational teacher education', 'btvted');
  alias('bachelor of technology and livelihood education', 'btled');
  alias('juris doctor', 'jd');
  alias('doctor of medicine', 'md');
  alias('doctor of dental medicine', 'dmd');
  alias('doctor of veterinary medicine', 'dvm');
  alias('doctor of optometry', 'od');

  const keywords = <String, String>{
    'information technology': ' it bsit ',
    'computer science': ' cs bscs ',
    'information systems': ' is bsis ',
    'accountancy': ' bsa ',
    'nursing': ' bsn ',
    'civil engineering': ' ce ',
    'psychology': ' psych ',
    'criminology': ' crim ',
    'hospitality management': ' bshm ',
    'hotel and restaurant management': ' hrm bshrm ',
    'business administration': ' bsba ',
    'public administration': ' bpa ',
    'medical technology': ' medtech ',
    'medical laboratory science': ' mls medtech ',
    'elementary education': ' beed ',
    'secondary education': ' bsed ',
    'industrial security management': ' bsism ',
  };
  for (final entry in keywords.entries) {
    if (lower.contains(entry.key)) extra.write(entry.value);
  }
  return extra.toString();
}

