  kCourseOrStrandOptions.map((option) => option.label),
);

final Map<String, String> _courseOrStrandGroups = {
  for (final option in kCourseOrStrandOptions) option.label: option.group,
};

String? courseOrStrandGroup(String option) => _courseOrStrandGroups[option];

/// College aliases plus SHS abbreviations that are not already in the label.
String courseOrStrandSearchText(String option) {
  final extra = StringBuffer(philippineCourseSearchText(option));
  final lower = option.toLowerCase();
  if (lower.contains('science, technology, engineering')) {
    extra.write(' stem ');
  }
  if (lower.contains('technical-professional') || lower.contains('techpro')) {
    extra.write(' techpro technical professional ');
  }
  if (lower.contains('information and communications technology')) {
    extra.write(' ict ');
  }
  if (lower.contains('accountancy, business and management')) {
    extra.write(' abm ');
  }
  if (lower.contains('humanities and social sciences')) {
    extra.write(' humss ');
  }
  if (lower.contains('general academic strand')) extra.write(' gas ');
  return extra.toString();
}
